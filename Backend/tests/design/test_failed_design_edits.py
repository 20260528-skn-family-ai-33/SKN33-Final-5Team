def popup(reader, old=100, new=5):
    return (f"`{reader['label']}` 작업 (노드 ID: {reader['id']})의 설정을 다음과 같이 바꿔줘.\n"
            f'- 조회 한도 (arguments_json.max_results): {old} → {new}\n'
            '다른 작업의 설정은 유지해줘.')


def reviewed_mail():
    state, _ = interpreted('gmail에서 안읽은 메일 요약 정리해줘',
                           meaning(count=None, evidence=None, filters=['unread']))
    state.update(gmail_summary_reply(state))
    return state


def test_popup_count_edit_reuses_reviewed_unread_scope_without_another_model():
    state = reviewed_mail()
    old = deepcopy(state['draft'])
    state['messages'].append({'role':'user', 'content':popup(old['workflow']['nodes'][0])})
    class UnexpectedModel:
        def invoke(self, messages):
            pytest.fail('A proven count-only edit must not call the model again')
    state.update(make_meaning_node('fixture', transport=UnexpectedModel())(state))
    result = gmail_summary_reply(state)
    assert result is not None
    args = json.loads(result['draft']['workflow']['nodes'][0]['settings']['arguments_json'])
    assert args == {'max_results':5, 'query':'is:unread -in:sent -in:drafts'}
    assert result['draft']['workflow']['edges'] == old['workflow']['edges']
    assert state['draft'] == old
    assert validate_node({**state, **result})['status'] == 'ready'


def test_full_graph_popup_count_edit_preserves_the_ready_gmail_workflow(tmp_path):
    from agent_builder.design.graph import build_graph
    from infrastructure.persistence.storage import Storage
    from langgraph.types import Command
    from tests.design.test_request_meaning import Extractor as MeaningExtractor
    store = Storage(tmp_path)
    model = MeaningExtractor(meaning(count=None, evidence=None, filters=['unread']))
    def unexpected_planner(state):
        pytest.fail('The verified Gmail workflow should not be regenerated by the planner')
    graph, connection = build_graph(store, conversation=unexpected_planner, meaning_transport=model,
        capability_mode='off', condition_mode='off', requirement_mode='enforce', verifier_mode='off')
    state = {**initial(), 'messages':[{'role':'user','content':'gmail에서 안읽은 메일 요약 정리해줘'}]}
    config = {'configurable':{'thread_id':state['session_id']}}
    try:
        first = graph.invoke(state, config)
        assert first['status'] == 'ready'
        count = len(model.messages)
        revised = graph.invoke(Command(resume={'type':'message',
            'content':popup(first['draft']['workflow']['nodes'][0])}), config)
        assert revised['status'] == 'ready'
        assert not revised.get('requirement_failure')
        args = json.loads(revised['draft']['workflow']['nodes'][0]['settings']['arguments_json'])
        assert args == {'max_results':5, 'query':'is:unread -in:sent -in:drafts'}
        assert len(model.messages) == count
        assert len(revised['draft']['workflow']['nodes']) == 2
    finally:
        connection.close()
        store.close()


@pytest.mark.parametrize('change', ['node', 'old', 'too_large', 'zero', 'additional_work'])
def test_popup_count_fast_path_rejects_stale_targets_and_additional_work(change):
    state = reviewed_mail()
    reader = deepcopy(state['draft']['workflow']['nodes'][0])
    if change == 'node':
        reader['id'] = 'different-reader'
    text = popup(reader, old=99 if change == 'old' else 100,
                 new=501 if change == 'too_large' else 0 if change == 'zero' else 5)
    if change == 'additional_work':
        text += '\n그리고 결과를 메일로 보내줘.'
    assert _popup_count_evidence(state, text) is None


def test_requirement_failure_retains_previous_draft_and_explains_actual_stage_on_retry():
    state = current('보고서 작업의 조건을 바꿔줘.', 'manual')
    original = reviewed_mail()['draft']
    state['draft'] = deepcopy(original)
    model = Extractor({'tasks':'bad_schema_field', 'unresolved':[]})
    check = make_requirement_check('fixture', model, 'enforce')
    failed = check(state)
    assert failed['draft'] == original
    assert failed['status'] == 'validation_failed' and not failed['confirmed']
    assert failed['requirement_failure']['stage'] == 'requirements'
    assert failed['requirement_failure']['attempt'] == 1
    notice = failed['messages'][-1]['content']
    assert '작업 목록' in notice and '잘못된 형식' in notice
    assert '이전 워크플로우 초안은 유지' in notice and '아직 적용되지' in notice
    assert 'bad_schema_field' not in json.dumps(failed)
    again = check({**state, **failed})
    assert again['draft'] == original
    assert again['requirement_failure']['attempt'] == 2
    assert '2번째 시도도 실패' in again['messages'][-1]['content']
    assert len(model.calls) == 4


def test_legacy_failed_draft_is_recovered_without_becoming_ready_or_mutating_checkpoint():
    prior = reviewed_mail()
    prior['status'] = 'ready'
    failed = {**prior, 'status':'validation_failed', 'draft':None, 'request_meaning':None,
              'requirement_failure':{'kind':'processing_error', 'retryable':True}}
    class History:
        def get_state_history(self, config, limit):
            return iter([SimpleNamespace(values=failed, next=()), SimpleNamespace(values=prior, next=('await_approval',))])
    recovered = retained_design(failed, History(), {})
    assert recovered['draft'] == prior['draft']
    assert recovered['status'] == 'validation_failed'
    assert recovered['request_meaning'] == prior['request_meaning']
    assert failed['draft'] is None
    recovered['draft']['name'] = 'changed copy'
    assert prior['draft']['name'] != 'changed copy'


