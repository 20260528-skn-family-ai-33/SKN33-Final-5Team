def test_legacy_failure_reopens_and_retries_original_edit_without_losing_ready_draft(tmp_path, monkeypatch):
    from service.worker import handle
    import service.handlers.design as worker
    from infrastructure.persistence.storage import Storage
    from infrastructure.persistence.ids import uid
    from tests.design.test_builder import draft, PROMPT
    from workflow_engine.workflow import legacy_workflow
    from langgraph.types import Command

    real = worker.build_graph
    model = Extractor({'tasks':'invalid', 'unresolved':[]})
    def graph(*args, **kwargs):
        return real(*args, **{**kwargs, 'capability_mode':'off', 'condition_mode':'off',
                            'requirement_mode':'off', 'verifier_mode':'off', 'requirement_transport':model})
    monkeypatch.setattr(worker, 'build_graph', graph)
    def planner(_):
        value = draft()
        value['workflow'] = legacy_workflow(value)
        return {'draft':value}
    session = handle(dict(directory=str(tmp_path), action='new_session', model='fixture', credential_id=uid()))
    job = dict(directory=str(tmp_path), id=session['id'], revision=0, action='message')
    ready = handle({**job, 'content':PROMPT}, conversation=planner)
    assert ready['status'] == 'ready'
    config = {'configurable':{'thread_id':session['id']}}
    store = Storage(tmp_path)
    built, connection = graph(store, conversation=planner)
    try:
        built.update_state(config, {'requirement_required':True})
        failure = built.invoke(Command(resume={'type':'message','content':'조회 건수만 수정해줘.'}),config)
        assert failure['status'] == 'validation_failed'
        # Reproduce the already deployed behavior that erased the prior draft.
        built.update_state(config, {'draft':None}, as_node='requirements')
    finally:
        connection.close()
        store.close()
    reopened = handle({**job, 'action':'session'})
    assert reopened['draft'] == ready['draft'] and reopened['status'] == 'validation_failed'
    retried = handle({**job, 'revision':ready['revision'],
                      'content':'앞서 전달한 조건을 유지하고 업무 흐름 생성을 다시 시도해주세요.'},
                     conversation=planner)
    assert retried['draft'] == ready['draft']
    assert retried['status'] == 'validation_failed'
    assert retried['requirement_failure']['attempt'] == 2
    assert [m['content'] for m in retried['messages'] if m['role']=='user'] == [PROMPT, '조회 건수만 수정해줘.']
    assert len(model.calls) == 4
    with pytest.raises(ValueError):
        handle({**job, 'action':'confirm', 'revision':retried['revision']})
    assert handle({**job, 'action':'session'})['draft'] == ready['draft']


def test_popup_count_evidence_survives_the_count_already_applied_to_the_draft():
    state = reviewed_mail()
    text = popup(state['draft']['workflow']['nodes'][0])
    assert _popup_count_evidence(state, text) == (5, '5')
    applied = deepcopy(state)
    node = applied['draft']['workflow']['nodes'][0]
    args = json.loads(node['settings']['arguments_json'])
    node['settings']['arguments_json'] = json.dumps({**args, 'max_results':5}, ensure_ascii=False)
    assert _popup_count_evidence(applied, text) == (5, '5')
    node['label'] = node['label'].replace('100건', '5건')
    assert _popup_count_evidence(applied, text) == (5, '5')
    node['settings']['arguments_json'] = json.dumps({**args, 'max_results':7}, ensure_ascii=False)
    assert _popup_count_evidence(applied, text) is None


